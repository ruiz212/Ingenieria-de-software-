"""Build explicitly ordered CSS packages. Run with --check to detect stale assets."""
import argparse
import hashlib
import json
from pathlib import Path


def _inside(root, relative):
    path = (root / relative).resolve()
    if not path.is_relative_to(root) or path == root:
        raise ValueError(f'Ruta CSS fuera del directorio permitido: {relative}')
    return path


def build_css(base_dir=None, *, check=False):
    root = Path(base_dir or Path(__file__).resolve().parents[1] / 'static' / 'css').resolve()
    packages = json.loads((root / 'sources.json').read_text(encoding='utf-8'))
    rendered = {}
    manifest = {}
    # Validate every source before changing any generated file.
    for name, sources in packages.items():
        if not name or any(part in ('', '.', '..') for part in name.split('/')):
            raise ValueError(f'Nombre de paquete CSS no válido: {name}')
        target = _inside(root, f'dist/{name}.css')
        if len(sources) != len(set(sources)):
            raise ValueError(f'Fuente CSS repetida en {name}')
        parts = ['/* Generated by scripts/build_css.py. Edit the named sources. */\n']
        for source in sources:
            path = _inside(root, source)
            if path.suffix != '.css' or path.is_relative_to(root / 'dist'):
                raise ValueError(f'Fuente CSS no válida: {source}')
            parts.append(f'\n/* Source: {source} */\n{path.read_text(encoding="utf-8").strip()}\n')
        content = ''.join(parts).encode('utf-8')
        rendered[target] = content
        manifest[name] = {'file':target.relative_to(root).as_posix(),
                          'version':hashlib.sha256(content).hexdigest()[:12]}
    rendered[root / 'dist' / 'manifest.json'] = (json.dumps(manifest, indent=2, ensure_ascii=False) + '\n').encode('utf-8')
    if check:
        for target, content in rendered.items():
            if not target.exists() or target.read_bytes() != content:
                raise ValueError(f'CSS desactualizado: {target.relative_to(root)}. Ejecute python scripts/build_css.py')
    else:
        for target, content in rendered.items():
            target.parent.mkdir(parents=True, exist_ok=True)
            pending = target.with_suffix(target.suffix + '.tmp')
            pending.write_bytes(content)
            pending.replace(target)
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Validate generated files without writing')
    options = parser.parse_args()
    assets = build_css(check=options.check)
    print(f'CSS: {len(assets)} paquetes {"verificados" if options.check else "generados"}.')
